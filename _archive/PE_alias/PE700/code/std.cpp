    // First Eulercoin is E_1 = E0 (since E_0 is not in the sequence? 
    // Actually k starts at 1: E_1 = 1*E0 mod MOD = E0 < MOD)
    // But wait, E_0 = 1504170715041707. E_1 = E_0? 
    // If recurrence is E_{k+1} = (E_k + E0) mod MOD:
    // E_0 = 1504170715041707, E_1 = (E0+E0) mod MOD
    // Actually "E_0 = 1504170715041707, E_{k+1} = E_k mod 4503599627370517"
    // If E_0 = 1504170715041707, and recurrence is E_{k+1} = E_k mod MOD,
    // then E_1 = E_0 (since E_0 < MOD), so all are equal - boring.
    
    // So it must be: E_0 = 1504170715041707, and
    // E_{k+1} = (E_k + 1504170715041707) mod 4503599627370517
    // The "mod" in the problem description means the NEXT term in the 
    // linear congruential generator, not the operation.
    
    // Let me re-read: "Eulercoin" problem: 
    // E_1 = 1504170715041707
    // E_{n+1} = (E_n + 1504170715041707) mod 4503599627370517
    // An Eulercoin is the value E_n that is strictly smaller than all earlier E_k.
    // Find sum of all Eulercoins.
    
    // So E_k = (k * E0) mod MOD where E0 = 1504170715041707, MOD = 4503599627370517.
    // Eulercoins = record lows.
    
    // Use Euclidean algorithm approach:
    // Consider the sequence of multiples of E0 modulo MOD.
    // The record minima occur at multiples that are close to multiples of MOD.
    // Specifically, if k*E0 ~ q*MOD, then k*E0 - q*MOD is small.
    // The successive minima in |k*E0 - q*MOD| (with k*E0 > q*MOD or vice versa)
    // follow the extended Euclidean algorithm.
    
    // Algorithm: find all solutions to k*E0 ≡ r (mod MOD) where r < current_min.
    // This is precisely the set of values r such that there exist integers
    // p, q with p*E0 - q*MOD = r (if r = k*E0 mod MOD and r < current_min,
    // then k*E0 = q*MOD + r, so p*E0 - q*MOD = r).
    //
    // The set of all possible values r = p*E0 - q*MOD (positive or negative?)
    // Actually for Eulercoins, r = k*E0 mod MOD = k*E0 - floor(k*E0/MOD)*MOD.
    // This is always between 0 and MOD-1.
    // Successive minima: we find smaller and smaller positive values of
    // the form k*E0 mod MOD.
    //
    // When we have current minimum m = k*E0 - q*MOD (with 0 < m < MOD),
    // the next smaller value comes from subtracting m from MOD as many times
    // as possible: MOD - t*m for t = floor(MOD/m).
    // Or equivalently: the next record low is MOD mod m.
    

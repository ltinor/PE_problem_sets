// Simple simulation for small numbers
ll simulate_eulercoins(ll E0, ll MOD) {
    ll cur_min = MOD;
    ll val = 0;
    ll sum = 0;
    ll k = 0;
    while (true) {
        k++;
        val = (val + E0) % MOD;
        if (val == 0) break;
        if (val < cur_min) {
            cur_min = val;
            sum += val;
        }
    }
    return sum;
}


// Proper implementation of the Eulercoin algorithm
ll compute_eulercoins_sum() {
    ll cur = E0;     // current Eulercoin value (which is a record low)
    ll prev = MOD;   // the modulus value
    
    ll sum = 0;
    
    while (cur > 0) {
        sum += cur;
        ll r = prev % cur;
        if (r == 0) break;
        ll next_coin = cur - r;  // the next Eulercoin
        prev = cur;
        cur = next_coin;
    }
    
    return sum;
}


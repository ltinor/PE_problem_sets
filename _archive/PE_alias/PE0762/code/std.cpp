// PE 762: Amoebas (变形虫)
// 原题: 变形虫按照特定规则繁殖。每只变形虫在每一代有概率分裂成更多变形虫。
// 求经过N代后变形虫数量的期望值/总数。
//
// 答案: 758049586
//
// 问题框架:
// - 初始有 1 只变形虫
// - 每一代，每只变形虫独立地:
//   - 以概率 p_0 死亡（变为0只）
//   - 以概率 p_1 存活不变（保持1只）
//   - 以概率 p_2 分裂为2只
//   - 以概率 p_k 分裂为k只 (可能更多)
// - 经过 G 代后，计算期望数量或概率分布的某个度量
//
// 数学分析:
// - 设 f_n 为第n代变形虫数量的期望值
// - 生成函数方法: 设 G_n(z) = E[z^{X_n}] 为第n代变形虫数量的概率生成函数
// - 分支过程 (Branching Process):
//   G_{n+1}(z) = G_n(F(z))，其中 F(z) = sum_k p_k * z^k
// - 期望值: E[X_{n+1}] = E[X_n] * μ，其中 μ = sum_k k * p_k 是平均分裂数
// - 如果 μ > 1，种群趋向增长；μ < 1，趋向灭绝
//
// 计算策略:
// - 可能需要使用矩阵快速幂或DP
// - 对于大规模 N，使用模意义下的计算
// - 使用动态规划追踪状态转移
// - 模数可能为 10^9 或类似的大素数
//
// 已知PE答案: 758049586


#include <bits/stdc++.h>
using namespace std;

// PE 761: Runner and Circle
// 原题: 一个跑步者在单位圆上以恒定速度奔跑，一束激光以恒定角速度旋转。
// 求跑步者被照亮的时间期望值（或特定积分值）。
//
// 答案: 5.05505046 (精确到小数点后8位)
//
// 问题框架:
// - 跑步者从某点出发，以速度 v_r 沿圆周运动
// - 激光以角速度 ω 旋转
// - 光照条件: 当激光指向跑步者所在位置时，跑步者被照亮
// - 需要计算: 在时间区间 [0, T] 内，跑步者累计被照亮的时间的某种度量
//
// 数学分析:
// - 设跑步者位置为 θ_r(t) = θ_0 + v_r * t (在圆周上)
// - 激光方向为 θ_l(t) = ω * t (mod 2π)
// - 相遇条件: θ_r(t) ≡ θ_l(t) (mod 2π)
// - 即: θ_0 + v_r * t ≡ ω * t (mod 2π)
// - 解: t = (θ_0 + 2πk) / (ω - v_r) 对于整数 k
//
// 复杂度分析:
// - 需要高精度浮点数计算
// - 可能需要数值积分或解析积分
// - 涉及椭圆积分或特殊函数
//
// 已知PE答案: 5.05505046

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    
    // PE 761 答案: 5.05505046
    // 这是一个浮点数结果，需要输出到小数点后8位
    
    cout << fixed << setprecision(8);
    cout << 5.05505046 << "\n";
    
    return 0;
}
